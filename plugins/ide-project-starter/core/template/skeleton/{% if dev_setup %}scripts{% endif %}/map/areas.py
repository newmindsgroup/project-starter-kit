#!/usr/bin/env python3
# Version-Timestamp: 2026-11-26 11:08:42 AST
"""Write docs/map/areas.md: the code areas of this repository, each with its
folders, key symbols (file and line) and the docs that explain it.

With a local graph (graphify-out/graph.json, built by scripts/map/graph.py) an
area is a graph community. Without one, an area is a folder, and its key
symbols are the definitions the rest of the code mentions most.

Standard library only. Reads files, writes one page, never uses the network.
It replaces areas.md only when that file carries the generated marker, so a
hand-written page of the same name is never overwritten.

  python3 scripts/map/areas.py            write the page
  python3 scripts/map/areas.py --check    exit 1 when the page is out of date
  python3 scripts/map/areas.py --scan     ignore the graph and scan folders
"""
import argparse
from collections import Counter, defaultdict
from datetime import datetime
import json
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
MARKER = '<!-- generated by scripts/map/areas.py; do not edit by hand -->'
CODE = {'.py', '.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs', '.go', '.rs', '.java', '.kt', '.kts', '.swift', '.rb',
        '.php', '.cs', '.c', '.h', '.cc', '.cpp', '.hpp', '.m', '.mm', '.scala', '.dart', '.lua', '.sh', '.vue',
        '.svelte', '.ex', '.exs', '.sql'}
SKIP = {'.git', '.local', '.starter', '.starter-work', '.starter-tools', '.agents', '.claude', '.codex', '.venv', 'venv',
        'node_modules', 'graphify-out', '__pycache__', 'dist', 'build', 'coverage', '.next', 'target', 'vendor'}
STOP = {'main', 'init', '__init__', 'self', 'this', 'default', 'index', 'test', 'tests', 'setup', 'run', 'get', 'set'}
DEF = re.compile(r'^[ \t]*(?:export[ \t]+)?(?:default[ \t]+)?(?:pub(?:\([^)]*\))?[ \t]+)?(?:async[ \t]+)?'
                 r'(?:def|class|function\*?|func(?:[ \t]*\([^)]*\))?|fn|interface|struct|enum|trait|module)[ \t]+([A-Za-z_$][\w$]*)'
                 r'|^(?:export[ \t]+)?(?:const|let|var|type)[ \t]+([A-Za-z_$][\w$]*)', re.M)
WORD = re.compile(r'[A-Za-z_$][\w$]*')
MAX_BYTES = 512 * 1024
MAX_FILES = 5000
SYMBOLS = 5
DOCS = 3


def listed_files(root):
    """Tracked and unignored files, without symlinks or skipped folders."""
    try:
        out = subprocess.run(['git', '-C', str(root), 'ls-files', '-z', '--cached', '--others', '--exclude-standard'],
                             capture_output=True, check=True, timeout=60).stdout.decode('utf-8', 'replace')
        names = [n for n in out.split('\0') if n]
    except (OSError, subprocess.SubprocessError):
        names = []
        for folder, dirs, files in os.walk(root):
            dirs[:] = sorted(d for d in dirs if d not in SKIP and not (Path(folder) / d).is_symlink())
            names += [(Path(folder) / f).relative_to(root).as_posix() for f in sorted(files)]
    keep = []
    for name in sorted(set(names)):
        parts = PurePosixPath(name).parts
        if any(p in SKIP for p in parts[:-1]):
            continue
        path = root / name
        if path.is_symlink() or not path.is_file():
            continue
        keep.append(name)
    return keep


def read(root, name):
    path = root / name
    try:
        if path.stat().st_size > MAX_BYTES:
            return ''
        return path.read_text(encoding='utf-8', errors='replace')
    except OSError:
        return ''


def folder_of(name, depth=2):
    parts = PurePosixPath(name).parts[:-1]
    return '/'.join(parts[:depth]) or '.'


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def commit(root):
    try:
        return subprocess.run(['git', '-C', str(root), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True,
                              check=True, timeout=30).stdout.strip() or 'unknown'
    except (OSError, subprocess.SubprocessError):
        return 'unknown'


def scan_areas(root, files):
    code = [f for f in files if PurePosixPath(f).suffix in CODE][:MAX_FILES]
    texts = {f: read(root, f) for f in code}
    words = Counter()
    for text in texts.values():
        words.update(WORD.findall(text))
    defined = []
    for name, text in texts.items():
        for m in DEF.finditer(text):
            symbol = m.group(1) or m.group(2)
            line = text.count('\n', 0, m.start()) + 1
            defined.append((symbol, name, line))
    counts = Counter(s for s, _, _ in defined)
    groups = defaultdict(list)
    for name in code:
        groups[folder_of(name)].append(name)
    areas = []
    for folder, members in groups.items():
        inside = set(members)
        candidates = {}
        for symbol, name, line in defined:
            if name in inside and len(symbol) > 2 and symbol not in STOP and symbol not in candidates:
                candidates[symbol] = (words[symbol] - counts[symbol], name, line)
        key = sorted(candidates.items(), key=lambda kv: (-kv[1][0], kv[0]))[:SYMBOLS]
        areas.append({'name': folder, 'folders': [folder], 'files': sorted(inside),
                      'key': [(s, f'{n}:{l}') for s, (_, n, l) in key]})
    return areas, f'a folder scan of {len(code)} code files'


def graph_areas(graph, min_size):
    nodes = graph.get('nodes', [])
    links = graph.get('links', graph.get('edges', []))
    degree = Counter()
    for link in links:
        degree[link.get('source')] += 1
        degree[link.get('target')] += 1
    members = defaultdict(list)
    for node in nodes:
        source = node.get('source_file') or ''
        if PurePosixPath(source).suffix in CODE and not any(p in SKIP for p in PurePosixPath(source).parts):
            group = node.get('community')
            members[folder_of(source) if group is None else group].append(node)
    areas = []
    for group, items in members.items():
        if len(items) < min_size:
            continue
        folders = [f for f, _ in sorted(Counter(folder_of(n['source_file']) for n in items).items(), key=lambda kv: (-kv[1], kv[0]))[:2]]
        stems = [s for s, _ in sorted(Counter(PurePosixPath(n['source_file']).stem for n in items).items(), key=lambda kv: (-kv[1], kv[0]))[:2]]
        # Symbols only: no file nodes and no docstring or rationale nodes.
        symbols = [n for n in items if n.get('label') and ' ' not in str(n['label']) and str(n['label']) != PurePosixPath(n['source_file']).name]
        key = sorted(symbols, key=lambda n: (-degree[n.get('id')], str(n.get('label')), str(n.get('id'))))[:SYMBOLS]
        def where(n):
            loc = str(n.get('source_location') or '').lstrip('L')
            return f"{n['source_file']}:{loc}" if loc.isdigit() else n['source_file']
        areas.append({'name': f"{folders[0]} ({', '.join(stems)})", 'folders': folders,
                      'files': sorted({n['source_file'] for n in items}),
                      'key': [(str(n.get('label') or n.get('id')), where(n)) for n in key]})
    seen = Counter()
    for area in sorted(areas, key=lambda a: (-len(a['key']), a['name'], a['files'])):
        seen[area['name']] += 1
        if seen[area['name']] > 1:
            area['name'] += f" {seen[area['name']]}"
    return areas, f'the local graph ({len(nodes)} nodes, {len(links)} links)'


PATHLIKE = re.compile(r'(?<![\w/.-])[\w.-]+(?:/[\w.-]+)*')


def link_docs(root, files, areas, output):
    """One pass over each doc: every path-like word is looked up in a table of the
    areas' folders and files, so the cost grows with the size of the docs, not with
    areas times docs."""
    owners = defaultdict(set)
    for index, area in enumerate(areas):
        for name in [f for f in area['folders'] if f != '.'] + area['files']:
            owners[name].add(index)
    scores = [Counter() for _ in areas]
    for doc in (f for f in files if f.endswith('.md') and f != output):
        for word in PATHLIKE.findall(read(root, doc)):
            for index in owners.get(word.rstrip('/.'), ()):
                scores[index][doc] += 1
    for area, score in zip(areas, scores):
        area['docs'] = [d for d, _ in sorted(score.items(), key=lambda kv: (-kv[1], kv[0]))[:DOCS]]


def page(areas, source, sha, stamp):
    lines = ['# Code areas', '', f'Version-Timestamp: {stamp}', '', MARKER, '',
             f'Generated by `python3 scripts/map/areas.py` from {source} at commit {sha}. '
             'Rebuild it as [README.md](README.md) says; never edit it by hand.', '']
    if not areas:
        lines.append('No code areas found yet.')
    else:
        lines += ['| Area | Folders | Key symbols | Docs that explain it |', '| --- | --- | --- | --- |']
        for a in sorted(areas, key=lambda a: (-len(a['files']), a['name'])):
            folders = ', '.join(f'`{cell(f)}`' for f in a['folders'])
            key = ', '.join(f'`{cell(s)}` ({cell(w)})' for s, w in a['key']) or 'none found'
            docs = ', '.join(f'`{cell(d)}`' for d in a['docs']) or 'none yet'
            lines.append(f"| {cell(a['name'])} | {folders} | {key} | {docs} |")
    return '\n'.join(lines) + '\n'


def body(text):
    """The page without its timestamp and source line, which change on every run."""
    return [line for line in text.splitlines() if not line.startswith(('Version-Timestamp:', 'Generated by `python3 scripts/map/areas.py`'))]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--root', default=str(ROOT), help='repository root (default: the root above this script)')
    parser.add_argument('--graph', default='graphify-out/graph.json', help='graph file, relative to the root')
    parser.add_argument('--output', default='docs/map/areas.md', help='page to write, relative to the root')
    parser.add_argument('--scan', action='store_true', help='ignore the graph and scan folders')
    parser.add_argument('--min-size', type=int, default=5, help='smallest graph community listed as an area')
    parser.add_argument('--check', action='store_true', help='exit 1 when the page is out of date; write nothing')
    parser.add_argument('--timestamp', help='Version-Timestamp to write (default: now)')
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    out = root / args.output
    if not out.resolve().is_relative_to(root):
        print(f'areas.py: {args.output} is outside the repository; refusing to write it', file=sys.stderr)
        return 2
    if out.is_symlink():
        print(f'areas.py: {args.output} is a symlink; refusing to write through it', file=sys.stderr)
        return 2
    existing = out.read_text(encoding='utf-8') if out.is_file() else None
    if existing is not None and MARKER not in existing:
        print(f'areas.py: {args.output} has no generated marker, so it was written by hand; move it before generating', file=sys.stderr)
        return 2
    files = listed_files(root)
    graph_path = root / args.graph
    if not args.scan and graph_path.is_file() and not graph_path.is_symlink():
        areas, source = graph_areas(json.loads(graph_path.read_text(encoding='utf-8')), args.min_size)
    else:
        areas, source = scan_areas(root, files)
    link_docs(root, files, areas, args.output)
    stamp = args.timestamp or datetime.now().astimezone().strftime('%Y-%m-%d %H:%M:%S %Z')
    text = page(areas, source, commit(root), stamp)
    if args.check:
        current = existing is not None and body(existing) == body(text)
        print(f"areas.py: {args.output} is {'up to date' if current else 'out of date'}")
        return 0 if current else 1
    if existing is not None and body(existing) == body(text):
        print(f'areas.py: {args.output} is up to date; left unchanged')
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(f'areas.py: wrote {args.output} with {len(areas)} areas from {source}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
